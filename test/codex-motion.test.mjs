import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {createDocument,loadBundle} from './harness.mjs';
const {createCodexMotion}=loadBundle(fileURLToPath(new URL('../lib/client.js',import.meta.url)),createDocument()).plugin.__internals;
assert.equal(typeof createCodexMotion,'function','GPT has a continuous motion clock');
const motion=createCodexMotion();
const css=loadBundle(fileURLToPath(new URL('../lib/client.js',import.meta.url)),createDocument()).plugin.__internals.CSS;
assert.ok(!/\.ces-codex \.ces-star\{[^}]*transition:opacity/.test(css),'per-frame edge fading must not be delayed by a CSS transition when wrapping');
const initial=Array.from({length:22},(_,i)=>motion.point(i));
assert.ok(initial.every(p=>p.x>=0&&p.x<=100&&p.y>=0&&p.y<=100));
assert.ok(new Set(initial.map(p=>Math.floor(p.x/10))).size>=9,'particles cover the full illuminated area evenly');
motion.advance(1,false,1);
const floating=initial.map((_,i)=>motion.point(i));
assert.ok(floating.some((p,i)=>Math.abs(p.x-initial[i].x)>.01||Math.abs(p.y-initial[i].y)>.01),'standard maximum particles gently float');
assert.ok(floating.every((p,i)=>Math.abs(p.x-initial[i].x)<3&&Math.abs(p.y-initial[i].y)<5),'standard motion stays small, not a cross-track stream');
const before=motion.point(10);
motion.advance(0,true,1);
assert.deepEqual(motion.point(10),before,'turning fast on never resets position or brightness');
motion.advance(.016,true,1);
assert.ok(Math.abs(motion.point(10).x-before.x)<.15,'acceleration starts gently');
for(let i=0;i<120;i++)motion.advance(1/60,true,1);
const fast=motion.point(10);motion.advance(.1,true,1);
assert.ok(Math.abs(motion.point(10).x-fast.x)>2,'settled fast mode visibly flows');
const off=motion.point(10);motion.advance(0,false,1);
assert.deepEqual(motion.point(10),off,'turning fast off preserves position and brightness');
motion.advance(.016,false,1);
assert.ok(Math.abs(motion.point(10).x-off.x)>.1,'switching off decelerates instead of abruptly stopping');
for(let i=0;i<300;i++)motion.advance(1/60,false,1);
const settled=motion.point(10);motion.advance(.1,false,1);
assert.ok(Math.abs(motion.point(10).x-settled.x)<.25,'after deceleration only gentle suspension remains');
console.log('GPT particle distribution, suspension, continuous acceleration and deceleration passed');
